import math

# Ввод координат первой точки A
x1 = float(input("Введите координату x первой точки A: "))
y1 = float(input("Введите координату y первой точки A: "))

# Ввод координат второй точки B
x2 = float(input("Введите координату x второй точки B: "))
y2 = float(input("Введите координату y второй точки B: "))

# Расчет расстояния между точками по формуле Евклида
distance = math.sqrt((x2 - x1)**2 + (y2 - y1)**2)

# Расчет координат середины отрезка AB
middle_x = (x1 + x2) / 2
middle_y = (y1 + y2) / 2

# Вывод результатов
print("\n" + "="*50)
print("РЕЗУЛЬТАТЫ")
print("="*50)
print(f"Точка A: ({x1}, {y1})")
print(f"Точка B: ({x2}, {y2})")
print(f"Расстояние между точками: {distance:.2f}")
print(f"Координаты середины отрезка: ({middle_x}, {middle_y})")
print("="*50)
